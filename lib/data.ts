export const featuredProperties = properties.filter((p) => p.isFeatured);

export function getPropertyById(id: string): Property | undefined {
  return properties.find((p) => p.id === id);
}

export function getSimilarProperties(property: Property, limit = 3): Property[] {
  return properties
    .filter((p) => p.id !== property.id && (p.type === property.type || p.location.city === property.location.city))
    .slice(0, limit);
}

export function formatPrice(price: number, status: 'for-sale' | 'for-rent'): string {
  if (status === 'for-rent') {
    return `$${price.toLocaleString()}/mo`;
  }
  if (price >= 1000000) {
    return `$${(price / 1000000).toFixed(1)}M`;
  }
  return `$${price.toLocaleString()}`;
}
